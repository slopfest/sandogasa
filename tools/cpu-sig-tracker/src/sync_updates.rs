//! `sync-updates` subcommand: the list of updates on the SIG's site.
//!
//! Writes the Markdown table the Proposed Updates site includes
//! (`docs/content/updates-list.md`): one section per release, newest
//! first, one row per open tracking issue with a build in the SIG's
//! `-testing` or `-release` tag. The file is current state, rewritten
//! whole on every run and free of timestamps, so it changes in git only
//! when the state does.
//!
//! Nothing embargoed may leak through it. Tracking issues are listed
//! anonymously, so a confidential one is never seen, and its flag is
//! checked as well; an update whose Jira issue cannot be read
//! anonymously is left out, since Jira credentials can see what the
//! public cannot. Left out means no row at all, not a placeholder.

use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;
use std::process::ExitCode;

use crate::gitlab;
use crate::utils::{gitlab_base, jira_base};

/// GitLab group holding the per-package tracking projects.
const GROUP: &str = "CentOS/proposed_updates/rpms";

/// Label the tool puts on the tracking issues it files.
const TRACKING_LABEL: &str = "cpu-sig-tracker";

/// The type labels a tracking issue can carry.
const TYPE_LABELS: [&str; 4] = ["arch-enablement", "bugfix", "enhancement", "security"];

/// Releases always given a section, with or without updates.
const RELEASES: [&str; 2] = ["c10s", "c9s"];

/// The file's first line, telling a reader not to edit it.
const HEADER: &str = "<!-- Generated by cpu-sig-tracker sync-updates; do not edit by hand. -->";

#[derive(clap::Args)]
pub struct SyncUpdatesArgs {
    /// Print what would change in the file, without writing it
    #[arg(long)]
    pub dry_run: bool,

    /// The Markdown file to write, e.g. docs/content/updates-list.md
    #[arg(long, value_name = "PATH")]
    pub file: PathBuf,

    /// Name each lookup on stderr
    #[arg(short, long)]
    pub verbose: bool,
}

/// Where an update's build is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Stage {
    /// In the SIG's `-testing` tag only.
    Testing,
    /// In its `-release` tag.
    Released,
}

impl Stage {
    fn as_str(self) -> &'static str {
        match self {
            Stage::Testing => "testing",
            Stage::Released => "released",
        }
    }
}

/// One row of the list.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Update {
    pub package: String,
    pub issue_url: String,
    pub nvr: String,
    pub stage: Stage,
    /// The tracking issue's type label, if it has one.
    pub kind: Option<String>,
    pub cves: Vec<String>,
    /// The upstream merge request, as (iid, URL).
    pub mr: Option<(u64, String)>,
    /// The RHEL issues the update resolves, one per fix it carries.
    pub jira: Vec<String>,
}

/// A release and its updates: one section of the list.
pub type Section = (String, Vec<Update>);

/// `CentOS Stream 10` for `c10s`.
pub fn release_heading(release: &str) -> String {
    match release.strip_prefix('c').and_then(|r| r.strip_suffix('s')) {
        Some(n) => format!("CentOS Stream {n}"),
        None => release.to_string(),
    }
}

/// The releases to give sections, newest first: the two current ones
/// and any other an open issue is labelled with.
pub fn release_order(labelled: &BTreeSet<String>) -> Vec<String> {
    let mut all: BTreeSet<String> = RELEASES.iter().map(|r| r.to_string()).collect();
    all.extend(labelled.iter().cloned());
    let mut out: Vec<String> = all.into_iter().collect();
    let number = |r: &str| -> u32 {
        r.strip_prefix('c')
            .and_then(|r| r.strip_suffix('s'))
            .and_then(|n| n.parse().ok())
            .unwrap_or(0)
    };
    out.sort_by_key(|r| std::cmp::Reverse(number(r)));
    out
}

/// Every CVE id in `text`, upper-cased, in order of first mention.
pub fn cve_ids(text: &str) -> Vec<String> {
    let upper = text.to_ascii_uppercase();
    let mut out: Vec<String> = Vec::new();
    let mut rest = upper.as_str();
    while let Some(at) = rest.find("CVE-") {
        let tail = &rest[at + 4..];
        let year: String = tail.chars().take_while(|c| c.is_ascii_digit()).collect();
        if year.len() == 4 && tail[4..].starts_with('-') {
            let num: String = tail[5..]
                .chars()
                .take_while(|c| c.is_ascii_digit())
                .collect();
            let id = format!("CVE-{year}-{num}");
            if num.len() >= 4 && !out.contains(&id) {
                out.push(id);
            }
        }
        rest = &rest[at + 4..];
    }
    out
}

/// The `!N` a merge request URL ends in.
pub fn mr_iid(url: &str) -> Option<u64> {
    url.trim_end_matches('/')
        .rsplit_once("/merge_requests/")?
        .1
        .split(['?', '#', '/'])
        .next()?
        .parse()
        .ok()
}

/// The file's contents for `sections` of (release, updates), linking
/// Jira issues under `jira_site`.
pub fn render(sections: &[Section], jira_site: &str) -> String {
    let mut o = String::new();
    o.push_str(HEADER);
    o.push('\n');
    for (release, updates) in sections {
        o.push_str(&format!("\n# {}\n\n", release_heading(release)));
        if updates.is_empty() {
            o.push_str("No updates at the moment.\n");
            continue;
        }
        o.push_str("| Package | Build | Type | Fixes | Merge request | Jira | Status |\n");
        o.push_str("|---|---|---|---|---|---|---|\n");
        let mut sorted: Vec<&Update> = updates.iter().collect();
        // Case-insensitively: PackageKit among the p's, not first.
        sorted.sort_by_key(|u| (u.package.to_ascii_lowercase(), u.package.clone()));
        for u in sorted {
            let mr =
                u.mr.as_ref()
                    .map(|(iid, url)| format!("[!{iid}]({url})"))
                    .unwrap_or_default();
            let jira = u
                .jira
                .iter()
                .map(|k| format!("[{k}]({jira_site}/browse/{k})"))
                .collect::<Vec<_>>()
                .join(", ");
            o.push_str(&format!(
                "| [{}]({}) | `{}` | {} | {} | {mr} | {jira} | {} |\n",
                u.package,
                u.issue_url,
                u.nvr,
                u.kind.as_deref().unwrap_or(""),
                u.cves.join(", "),
                u.stage.as_str()
            ));
        }
    }
    o
}

/// A line diff of `old` against `new`, `-` and `+` lines with a space
/// for those kept: enough to read what a run would change in a file of
/// a few dozen lines.
pub fn line_diff(old: &str, new: &str) -> String {
    let a: Vec<&str> = old.lines().collect();
    let b: Vec<&str> = new.lines().collect();
    // Longest common subsequence, by table: the files are small.
    let mut lcs = vec![vec![0usize; b.len() + 1]; a.len() + 1];
    for i in (0..a.len()).rev() {
        for j in (0..b.len()).rev() {
            lcs[i][j] = if a[i] == b[j] {
                lcs[i + 1][j + 1] + 1
            } else {
                lcs[i + 1][j].max(lcs[i][j + 1])
            };
        }
    }
    let (mut i, mut j) = (0, 0);
    let mut out = String::new();
    while i < a.len() || j < b.len() {
        if i < a.len() && j < b.len() && a[i] == b[j] {
            out.push_str(&format!("  {}\n", a[i]));
            i += 1;
            j += 1;
        } else if j < b.len() && (i == a.len() || lcs[i][j + 1] >= lcs[i + 1][j]) {
            out.push_str(&format!("+ {}\n", b[j]));
            j += 1;
        } else {
            out.push_str(&format!("- {}\n", a[i]));
            i += 1;
        }
    }
    out
}

pub fn run(args: &SyncUpdatesArgs) -> ExitCode {
    match run_inner(args) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run_inner(args: &SyncUpdatesArgs) -> Result<(), Box<dyn std::error::Error>> {
    sandogasa_cli::require_tools(&[("koji", "sudo dnf install koji", None)])?;
    let sections = gather(args.verbose)?;
    let new = render(&sections, &jira_base());
    let old = std::fs::read_to_string(&args.file).unwrap_or_default();
    if old == new {
        println!("{} is up to date.", args.file.display());
        return Ok(());
    }
    if args.dry_run {
        println!("Would change {}:\n", args.file.display());
        print!("{}", line_diff(&old, &new));
        return Ok(());
    }
    std::fs::write(&args.file, &new)
        .map_err(|e| format!("cannot write {}: {e}", args.file.display()))?;
    println!("Wrote {}.", args.file.display());
    Ok(())
}

/// Every release's updates, read from GitLab, CBS Koji and Jira.
fn gather(verbose: bool) -> Result<Vec<Section>, Box<dyn std::error::Error>> {
    // Anonymous on purpose: a confidential issue is then never listed.
    let group = sandogasa_gitlab::GroupClient::new(&gitlab_base(), GROUP, "")?;
    if verbose {
        eprintln!("[cpu-sig-tracker] listing open tracking issues in {GROUP}");
    }
    let open = group.list_issues_where(&[("state", "opened")])?;
    let labelled: BTreeSet<String> = open
        .iter()
        .flat_map(|i| i.labels.iter())
        .filter(|l| l.starts_with('c') && l.ends_with('s') && l.len() > 2)
        .filter(|l| l[1..l.len() - 1].chars().all(|c| c.is_ascii_digit()))
        .cloned()
        .collect();
    let releases = release_order(&labelled);

    let runtime = crate::jira::runtime()?;
    let jira = sandogasa_jira::JiraClient::new(&jira_base());
    let mut out = Vec::new();
    for release in releases {
        let built = builds(&release, verbose);
        let mut updates: Vec<Update> = Vec::new();
        for issue in issues_for(&open, &release) {
            let Some(package) = gitlab::package_from_issue_url(&issue.web_url) else {
                continue;
            };
            let Some((nvr, stage)) = built.get(package).cloned() else {
                continue;
            };
            let body = issue.description.as_deref().unwrap_or("");
            let jira_keys = crate::utils::parse_jira_keys_from_body(body);
            // Any issue not public keeps the update off the list.
            let mut public = true;
            for key in &jira_keys {
                if verbose {
                    eprintln!("[cpu-sig-tracker] checking {key} is public");
                }
                match runtime.block_on(jira.issue(key)) {
                    Ok(Some(_)) => {}
                    Ok(None) => {
                        if verbose {
                            eprintln!(
                                "[cpu-sig-tracker] {package} ({release}) left out: {key} is \
                                 not public"
                            );
                        }
                        public = false;
                        break;
                    }
                    // Not known to be public is not public.
                    Err(e) => {
                        eprintln!(
                            "warning: {package} ({release}) left out: could not read {key} \
                             anonymously ({e})"
                        );
                        public = false;
                        break;
                    }
                }
            }
            if !public {
                continue;
            }
            let mr_url = crate::status::parse_mr_line(body)
                .map(|(u, _)| u)
                .or_else(|| crate::status::scan_mr_url_in_body(body));
            updates.push(Update {
                package: package.to_string(),
                issue_url: issue.web_url.clone(),
                nvr,
                stage,
                kind: issue
                    .labels
                    .iter()
                    .find(|l| TYPE_LABELS.contains(&l.as_str()))
                    .cloned(),
                cves: cve_ids(&format!("{}\n{body}", issue.title)),
                mr: mr_url.and_then(|u| mr_iid(&u).map(|iid| (iid, u))),
                jira: jira_keys,
            });
        }
        out.push((release, updates));
    }
    Ok(out)
}

/// The open, public tracking issues for `release`, one per package:
/// the tool's own when a package has one and a hand-filed one, the
/// first, otherwise.
fn issues_for<'a>(open: &'a [gitlab::Issue], release: &str) -> Vec<&'a gitlab::Issue> {
    let mut by_package: BTreeMap<&str, &gitlab::Issue> = BTreeMap::new();
    for issue in open
        .iter()
        .filter(|i| !i.confidential && i.labels.iter().any(|l| l == release))
    {
        let Some(package) = gitlab::package_from_issue_url(&issue.web_url) else {
            continue;
        };
        let ours = issue.labels.iter().any(|l| l == TRACKING_LABEL);
        match by_package.get(package) {
            Some(kept) if kept.labels.iter().any(|l| l == TRACKING_LABEL) || !ours => {}
            _ => {
                by_package.insert(package, issue);
            }
        }
    }
    by_package.into_values().collect()
}

/// Each package's build for `release`, from the SIG's tags: the newest
/// in `-release`, else the newest in `-testing`. A tag that cannot be
/// read is warned about and gives nothing.
fn builds(release: &str, verbose: bool) -> BTreeMap<String, (String, Stage)> {
    let mut out: BTreeMap<String, (String, Stage)> = BTreeMap::new();
    let tags = [
        (
            crate::dump_inventory::proposed_updates_tag(release),
            Stage::Released,
        ),
        (
            crate::dump_inventory::proposed_updates_testing_tag(release),
            Stage::Testing,
        ),
    ];
    for (tag, stage) in tags {
        let Ok(tag) = tag else { continue };
        if verbose {
            eprintln!("[cpu-sig-tracker] reading {tag}");
        }
        match sandogasa_koji::latest_tagged_all(&tag, Some("cbs")) {
            Ok(tagged) => {
                for b in tagged {
                    if let Some(name) = sandogasa_koji::parse_nvr_name(&b.nvr) {
                        out.entry(name.to_string())
                            .or_insert((b.nvr.clone(), stage));
                    }
                }
            }
            Err(e) => eprintln!("warning: could not read {tag}: {e}"),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn update(package: &str, stage: Stage) -> Update {
        Update {
            package: package.to_string(),
            issue_url: format!(
                "https://gitlab.com/CentOS/proposed_updates/rpms/{package}/-/issues/1"
            ),
            nvr: format!("{package}-1.0-1~proposed.el10"),
            stage,
            kind: Some("security".to_string()),
            cves: vec!["CVE-2025-1234".to_string()],
            mr: Some((
                123,
                format!(
                    "https://gitlab.com/redhat/centos-stream/rpms/{package}/-/merge_requests/123"
                ),
            )),
            jira: vec!["RHEL-12345".to_string()],
        }
    }

    #[test]
    fn the_list_is_sorted_and_an_empty_release_says_so() {
        let sections = vec![
            (
                "c10s".to_string(),
                vec![
                    update("zlib", Stage::Testing),
                    update("openssl", Stage::Released),
                    update("PackageKit", Stage::Released),
                ],
            ),
            ("c9s".to_string(), vec![]),
        ];
        let site = "https://redhat.atlassian.net";
        let text = render(&sections, site);
        let lines: Vec<&str> = text.lines().collect();
        assert_eq!(lines[0], HEADER);
        assert_eq!(lines[2], "# CentOS Stream 10");
        assert_eq!(
            lines[4],
            "| Package | Build | Type | Fixes | Merge request | Jira | Status |"
        );
        assert_eq!(
            lines[6],
            "| [openssl](https://gitlab.com/CentOS/proposed_updates/rpms/openssl/-/issues/1) \
             | `openssl-1.0-1~proposed.el10` | security | CVE-2025-1234 \
             | [!123](https://gitlab.com/redhat/centos-stream/rpms/openssl/-/merge_requests/123) \
             | [RHEL-12345](https://redhat.atlassian.net/browse/RHEL-12345) | released |"
        );
        assert!(lines[7].starts_with("| [PackageKit]"), "{text}");
        assert!(lines[8].starts_with("| [zlib]"), "{text}");
        assert!(lines[8].ends_with("| testing |"), "{text}");
        assert!(
            text.ends_with("# CentOS Stream 9\n\nNo updates at the moment.\n"),
            "{text}"
        );
        // The same state renders the same file: no timestamps.
        assert_eq!(render(&sections, site), text);
    }

    #[test]
    fn releases_are_newest_first_with_the_current_two_always_present() {
        assert_eq!(release_order(&BTreeSet::new()), ["c10s", "c9s"]);
        let labelled: BTreeSet<String> = ["c8s".to_string()].into();
        assert_eq!(release_order(&labelled), ["c10s", "c9s", "c8s"]);
        assert_eq!(release_heading("c10s"), "CentOS Stream 10");
    }

    #[test]
    fn cves_and_merge_requests_are_read_from_the_issue() {
        assert_eq!(
            cve_ids("freetype: Backport MR #8 for CVE-2025-27363\n- CVE-2025-27363, cve-2026-0001"),
            ["CVE-2025-27363", "CVE-2026-0001"]
        );
        assert!(cve_ids("no ids").is_empty());
        assert_eq!(
            mr_iid("https://gitlab.com/redhat/centos-stream/rpms/freetype/-/merge_requests/8"),
            Some(8)
        );
        assert_eq!(
            mr_iid("https://gitlab.com/x/-/merge_requests/8/diffs"),
            Some(8)
        );
        assert_eq!(mr_iid("https://gitlab.com/x/-/issues/8"), None);
    }

    #[test]
    fn confidential_issues_never_make_the_list() {
        let issue = |pkg: &str, labels: &[&str], confidential: bool| -> gitlab::Issue {
            serde_json::from_value(serde_json::json!({
                "iid": 1, "title": pkg, "description": null, "state": "opened",
                "web_url": format!("https://gitlab.com/CentOS/proposed_updates/rpms/{pkg}/-/issues/1"),
                "labels": labels, "confidential": confidential,
            }))
            .unwrap()
        };
        let open = vec![
            issue("openssl", &["c10s", "cpu-sig-tracker"], false),
            issue("embargoed", &["c10s", "cpu-sig-tracker"], true),
            issue("zlib", &["c9s"], false),
        ];
        let c10s: Vec<_> = issues_for(&open, "c10s")
            .into_iter()
            .map(|i| i.title.clone())
            .collect();
        assert_eq!(c10s, ["openssl"]);
        assert_eq!(issues_for(&open, "c9s").len(), 1);
    }

    #[test]
    fn the_dry_run_diff_shows_what_changes() {
        let diff = line_diff("a\nb\nc\n", "a\nc\nd\n");
        assert_eq!(diff, "  a\n- b\n  c\n+ d\n");
        assert_eq!(line_diff("", "x\n"), "+ x\n");
    }
}
